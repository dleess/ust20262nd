"""Render deposited coordinates for the lecture; no simulation or pose prediction."""
from pathlib import Path
import json
import pymol
from pymol import cmd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets' / 'figures'
pymol.finish_launching(['pymol', '-cq'])
cmd.set('max_threads', 4)
cmd.set('orthoscopic', 1)
cmd.set('ray_opaque_background', 1)
cmd.set('ray_shadows', 0)
cmd.set('antialias', 2)
cmd.set('specular', 0.15)
cmd.set('ambient', 0.55)
cmd.set('label_color', 'black')
cmd.set('label_size', 32)
cmd.set('label_font_id', 7)
cmd.set('label_outline_color', 'white')
cmd.set('label_connector', 1)
cmd.set('stick_radius', 0.20)
cmd.set('cartoon_fancy_helices', 1)
cmd.set_color('protein_c', [0.16, 0.52, 0.56])
cmd.set_color('drug_c', [0.88, 0.40, 0.10])
cmd.set_color('nitrogen_c', [0.15, 0.30, 0.84])
cmd.set_color('oxygen_c', [0.82, 0.13, 0.20])
cmd.set_color('contact_c', [0.42, 0.23, 0.56])
cmd.bg_color('white')

def colors(obj, ligand):
    cmd.color('protein_c', obj)
    cmd.color('drug_c', ligand)
    for elem, col in [('N', 'nitrogen_c'), ('O', 'oxygen_c'), ('S', 'yellow'), ('Cl', 'green'), ('F', 'cyan')]:
        cmd.color(col, f'{obj} and elem {elem}')
    cmd.set('cartoon_color', 'protein_c', obj)

def save(name, width=1800, height=1250):
    cmd.deselect()
    cmd.png(str(OUT / f'{name}.png'), width=width, height=height, dpi=180, ray=1, quiet=1)
    print(name, flush=True)

views = {}
for code, obj, lig_resn, met, leu, natom in [
    ('2ITY', 'egfr', 'IRE', '793', '718', 'N3'),
    ('1M17', 'test', 'AQ4', '769', '764', 'N2'),
]:
    cmd.reinitialize('everything')
    cmd.set('max_threads', 4)
    cmd.set('orthoscopic', 1)
    cmd.set('ray_opaque_background', 1)
    cmd.set('ray_shadows', 0)
    cmd.set('antialias', 2)
    cmd.set('specular', 0.15)
    cmd.set('ambient', 0.55)
    cmd.set('label_color', 'black')
    cmd.set('label_size', 32)
    cmd.set('label_font_id', 7)
    cmd.set('label_outline_color', 'white')
    cmd.set('label_connector', 1)
    cmd.set('stick_radius', 0.20)
    cmd.set('cartoon_fancy_helices', 1)
    cmd.set('surface_quality', 2)
    for name, rgb in [('protein_c',[.16,.52,.56]),('drug_c',[.88,.40,.10]),('nitrogen_c',[.15,.30,.84]),('oxygen_c',[.82,.13,.20]),('contact_c',[.42,.23,.56])]:
        cmd.set_color(name, rgb)
    cmd.bg_color('white')
    cmd.load(str(ROOT / 'assets' / 'structures' / f'{code}.pdb'), obj)
    cmd.remove('solvent')
    lig = f'{obj} and resn {lig_resn}'
    prot = f'{obj} and polymer.protein'
    near = f'byres ({prot} within 4.5 of ({lig}))'
    colors(obj, lig)
    cmd.hide('everything')
    cmd.show('cartoon', prot)
    cmd.show('sticks', lig)
    cmd.orient(obj)
    cmd.turn('y', 25)
    cmd.turn('x', -15)
    cmd.zoom(obj, 3)
    views[f'{code}_whole'] = list(cmd.get_view())
    save(f'{code}_whole')
    cmd.turn('y', 50)
    save(f'{code}_rotated')
    cmd.set_view(views[f'{code}_whole'])
    cmd.hide('cartoon')
    cmd.show('surface', prot)
    cmd.set('surface_color', 'protein_c', prot)
    cmd.set('transparency', 0.15)
    save(f'{code}_surface')
    cmd.hide('surface')
    cmd.show('sticks', prot)
    save(f'{code}_allsticks')
    cmd.hide('everything')
    cmd.show('sticks', lig)
    cmd.orient(lig)
    cmd.zoom(lig, 2)
    save(f'{code}_ligand')
    cmd.show('spheres', lig)
    cmd.hide('sticks')
    cmd.set('sphere_scale', 1)
    save(f'{code}_ligand_spheres')
    cmd.hide('everything')
    cmd.show('sticks', lig)
    cmd.show('sticks', near)
    cmd.show('cartoon', prot)
    cmd.set('cartoon_transparency', 0.80)
    cmd.orient(f'({lig}) or ({prot} and resi {met}+{leu})')
    cmd.zoom(f'({lig}) or ({prot} and resi {met}+{leu})', 5)
    cmd.turn('x', 10)
    views[f'{code}_pocket'] = list(cmd.get_view())
    save(f'{code}_neighbors')
    cmd.hide('cartoon')
    cmd.hide('sticks', prot)
    cmd.show('sticks', f'{prot} and resi {met}+{leu}')
    cmd.label(f'{prot} and resi {met} and name CA', f'"Met{met}"')
    cmd.label(f'{prot} and resi {leu} and name CA', f'"Leu{leu}"')
    cmd.set('label_position', [1.7, 1.7, 0])
    if code == '1M17':
        cmd.set('label_position', [-14, -3, 0], f'{prot} and resi {met} and name CA')
        cmd.set('label_size', 26, f'{prot} and resi {met} and name CA')
    save(f'{code}_contacts')
    cmd.distance('polar_contact', f'{prot} and resi {met} and name N', f'{lig} and name {natom}')
    cmd.set('dash_color', 'contact_c')
    cmd.set('dash_width', 5)
    cmd.set('dash_gap', 0.25)
    cmd.set('label_distance_digits', 1)
    cmd.set('label_position', [0, 0.8, 0], 'polar_contact')
    cmd.hide('labels', 'polar_contact')
    save(f'{code}_hbond')
    cmd.delete('polar_contact')
    cmd.hide('labels')
    cmd.hide('sticks', prot)
    cmd.show('surface', prot)
    cmd.set('transparency', 0.68)
    cmd.set('surface_color', 'protein_c', prot)
    save(f'{code}_pocket_surface')
    if code == '2ITY':
        cmd.hide('everything')
        fragment = f'{prot} and resi 790-795'
        cmd.show('sticks', fragment)
        cmd.orient(fragment)
        cmd.zoom(fragment, 3)
        save('peptide_fragment')
        cmd.hide('everything')
        single = f'{prot} and resi 793'
        cmd.show('sticks', single)
        cmd.show('spheres', single)
        cmd.set('sphere_scale', 0.23)
        cmd.orient(single)
        cmd.zoom(single, 2)
        cmd.color('drug_c', f'{single} and not name N+CA+C+O')
        cmd.hide('labels')
        save('methionine_residue')
        cmd.hide('everything')
        cmd.show('cartoon', prot)
        cmd.color('protein_c', prot)
        cmd.set('cartoon_transparency', 0)
        cmd.set('cartoon_color', -1)
        cmd.color('drug_c', f'{prot} and ss H')
        cmd.color('nitrogen_c', f'{prot} and ss S')
        cmd.orient(prot)
        cmd.zoom(prot, 3)
        save('secondary_egfr')
    cmd.save(str(ROOT / 'build' / f'{code}_teaching.pse'))
(ROOT / 'build' / 'views.json').write_text(json.dumps(views, indent=2))
cmd.quit()
